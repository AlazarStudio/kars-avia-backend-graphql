// Сравнение собранного патча с тем, что уже лежит в заявке: «изменилось ли
// вообще хоть что-нибудь». Нужно обновлению заявки, чтобы не писать документ,
// не заводить запись в историю и не рассылать участникам письмо, когда
// пользователь ничего не правил. Проверка «в патче есть хоть один ключ» этого
// не ловит: форма CRM шлёт все сервисные блоки безусловно, поэтому патч из неё
// непуст всегда.
//
// Смещение намеренно в безопасную сторону: любое сомнение — «изменилось».
// Ложное «изменилось» стоит лишнего письма, ложное «не изменилось» молча
// проглотит правку пользователя.

// Стабильная сериализация: ключи сортируются, даты приводятся к ISO, undefined
// отличается от null.
const stable = (value) => {
  if (value === undefined) return "__undef__"
  if (value === null) return "null"
  // Дата приводится к своей ISO-строке, а строки как даты НЕ разбираются. За
  // счёт этого Date и равная ей ISO-строка дают одну сериализацию (из Prisma
  // дата приходит объектом, из GraphQL — строкой), а строка, датой не
  // являющаяся, остаётся обычной строкой: «12» датой не станет.
  if (value instanceof Date) return JSON.stringify(value.toISOString())
  if (Array.isArray(value)) return `[${value.map(stable).join(",")}]`
  // Числа сериализуются отдельно: JSON.stringify превращает NaN и Infinity в
  // "null", и такое число сравнялось бы с настоящим null.
  if (typeof value === "number") return `#${value}`
  if (typeof value === "object") {
    return `{${Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${stable(value[key])}`)
      .join(",")}}`
  }
  return JSON.stringify(value)
}

// true — только если КАЖДЫЙ ключ патча уже имеет в заявке то же самое
// значение. Ключа, которого в заявке нет вовсе, достаточно для «изменилось».
export const patchIsNoop = (existing, data) =>
  Object.keys(data).every(
    (key) => stable(existing?.[key]) === stable(data[key])
  )
