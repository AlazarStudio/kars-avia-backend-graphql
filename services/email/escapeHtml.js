// Экранирование пользовательского текста, попадающего в HTML письма и сайтового
// уведомления. Локальные копии `esc` в соседних шаблонах письма старше этого
// модуля и трогаются отдельно — здесь только то, чем пользуются новые вызовы.
export function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
}
